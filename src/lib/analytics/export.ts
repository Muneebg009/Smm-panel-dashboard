import { csv } from "../finance/csv";
import type {
  AnalyticsResult,
  AnalyticsQuery,
  OrderRow,
  AggregateRow,
} from "./types";
export function analyticsCSV(result: AnalyticsResult, q: AnalyticsQuery) {
  const headers: (string | number | null)[][] = [
    [
      result.mode === "demo"
        ? "DEMO DATA — existing Phase 1 fixtures"
        : "LIVE ANALYTICS — verified fields only; unavailable metrics are blank-labeled",
    ],
    ["Availability", result.available ? "Available" : "Unavailable"],
    ["Reason", result.reason],
    ["Timezone", "Asia/Karachi"],
    ["Currency", q.currency],
    [
      "Date range (orders created, financial postings recognized within range)",
      q.start,
      q.end,
    ],
    ["Status", q.status],
    ["Search", q.search],
    ["Category", q.category],
    ["Provider filter", q.provider],
    ["Service status", q.serviceStatus],
    ["Ranking", q.view === "rankings" ? q.ranking : "Not applicable"],
    ["Sort", q.sort],
    [
      "Historical cost snapshots may be quoted; recognized provider costs are separate. Current service rates are not historical order costs.",
    ],
  ];
  if (q.view === "orders")
    return csv([
      ...headers,
      [
        "Order",
        "Service ID",
        "Service",
        "Provider ID",
        "Provider",
        "Provider source",
        "Created at",
        "Status",
        "Quantity",
        "Selling price",
        "Historical cost snapshot",
        "Cost basis",
        "Recognized revenue",
        "Recognized provider cost",
        "Gross profit",
        "Margin",
      ],
      ...(result.rows as OrderRow[]).map((o) => [
        o.id,
        o.serviceId,
        o.serviceName,
        o.providerId,
        o.providerName,
        o.providerSource,
        o.createdAt,
        o.status,
        o.quantity,
        o.sellingPrice,
        o.historicalCost,
        o.costBasis,
        o.recognizedRevenue,
        o.providerCosts,
        o.grossProfit,
        o.margin,
      ]),
    ]);
  return csv([
    ...headers,
    [
      "ID",
      "Name",
      "Category",
      "Provider ID",
      "Provider source",
      "Ordered quantity",
      "Orders",
      "Connected services",
      "Completed",
      "Partial",
      "Canceled",
      "Pending",
      "Processing",
      "Completion rate",
      "Cancellation rate",
      "Waiting rate",
      "Recognized revenue",
      "Provider costs",
      "Gross profit",
      "Gross margin",
      "Selling rate",
      "Provider rate",
      "Rate unit",
      "Rate margin",
      "Status",
      "Imported",
    ],
    ...(result.rows as AggregateRow[]).map((r) => [
      r.id,
      r.name,
      r.category,
      r.providerId,
      r.providerSource,
      r.quantity,
      r.orderCount,
      r.connectedServices,
      r.completed,
      r.partial,
      r.canceled,
      r.pending,
      r.processing,
      r.completionRate,
      r.cancellationRate,
      r.pendingRate,
      r.revenue,
      r.providerCosts,
      r.grossProfit,
      r.margin,
      r.sellingRate,
      r.providerRate,
      r.rateUnit,
      r.rateMargin,
      r.status,
      r.imported === null ? null : r.imported ? "Yes" : "No",
    ]),
  ]);
}
